"""
#------------------------------------------------------------------------------
# Модуль: TRANSPORT_BLOCK - Транспортный блок для сети LTE
#------------------------------------------------------------------------------
# Описание:
# Предоставляет структуру TransportBlock для хранения параметров передачи
# конкретному пользовательскому устройству (UE): индекса MCS, числа выделенных
# PRB, размера TBS в битах, содержимого буфера и полей для будущей поддержки HARQ.
# Расчёт размера транспортного блока делегируется модулю AMC.
#
# Версия: 1.0.0
# Дата последнего изменения: 2026-11-08
#
# Зависимости:
# - AMC.py (проверка входных параметров и табличный расчёт TBS)
# - dataclasses (структура TransportBlock и отдельный список buffer для каждого TB)
# Опосредованные зависимости:
# - GLOBALS.py (таблицы MCS -> I_TBS и TBS_TABLE, используемые модулем AMC)
#
# Основные компоненты:
# - TransportBlock: контейнер параметров и содержимого транспортного блока.
# - ue_id: идентификатор получателя.
# - mcs, rb, tbs: индекс MCS, число PRB и размер блока в битах.
# - buffer: список содержимого блока; автоматически из очередей не заполняется.
# - ndi, rv, harq_id: поля для интеграции с будущим механизмом HARQ.
# - determination_of_size_TB: пересчёт и сохранение tbs через AMC.get_tbs_bits.
#
# Текущее состояние v1.0.0:
# - TransportBlock размещён в отдельном модуле и доступен также через импорт
#   из SCHEDULER.py для совместимости.
# - Размер TB определяется по MCS 0..28 и числу PRB 1..110.
# - Неверные типы и диапазоны параметров расчёта отклоняются модулем AMC;
#   при ошибке прежнее значение tbs сохраняется.
# - Пересчёт размера не изменяет buffer и поля HARQ.
#
# Ограничения и дальнейшее развитие:
# - Создание объекта само по себе не рассчитывает tbs и не проверяет все поля;
#   для пересчёта необходимо вызвать determination_of_size_TB().
# - Формирование TB в рабочем цикле планировщика, наполнение из BufferManager
#   и согласование битового TBS с байтовыми грантами ещё не подключены.
# - ACK/NACK, переключение NDI/RV и повторные передачи не реализованы.
#------------------------------------------------------------------------------
"""

from dataclasses import dataclass, field
import AMC
from TRAFFIC_MODEL import Packet

@dataclass
class TransportBlock:
    ue_id: int
    tbs: int
    mcs: int
    rb: int
    buffer: list[Packet] = field(default_factory=list)
    ndi: int = 1
    rv: int = 0
    harq_id: int = 0        
    def determination_of_size_TB(self):
        self.tbs = AMC.get_tbs_bits(self.mcs, self.rb)
        return self.tbs

